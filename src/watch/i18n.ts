export const STRINGS: Record<Lang, Record<Key, string>> = { en, sw };

export type Vars = Record<string, string | number>;

/** Translate with {placeholders}. Server text is never passed through here as HTML. */
export function translate(lang: Lang, key: Key, vars?: Vars): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function lwErrorKey(code: LwCode, attemptsLeft?: number): Key {
  if (code === 'LW_OTP_WRONG' && typeof attemptsLeft === 'number') return 'err.LW_OTP_WRONG_LEFT';
  return `err.${code}` as Key;
}
export function signInErrorKey(kind: SignInErrorKind): Key { return `auth.err.${kind}` as Key; }
